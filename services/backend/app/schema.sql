-- Applied on every server start; every statement is idempotent.

-- One row per box (order) that has a checklist.
CREATE TABLE IF NOT EXISTS boxes (
    box_id     text PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Expected content of a box: what the camera client fetches as the checklist.
CREATE TABLE IF NOT EXISTS checklist_items (
    box_id   text NOT NULL REFERENCES boxes ON DELETE CASCADE,
    item_id  text NOT NULL,
    barcodes text[] NOT NULL DEFAULT '{}',  -- several barcodes can map to one item_id
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (box_id, item_id)
);

-- Results sent by the camera client. No FK to boxes: an NG for an unknown box is still recorded.
CREATE TABLE IF NOT EXISTS inspections (
    id           uuid PRIMARY KEY,  -- generated by the client, so a retried POST is not stored twice
    box_id       text NOT NULL,
    result       text NOT NULL CHECK (result IN ('OK', 'NG')),
    seal_status  text NOT NULL,
    qty          integer NOT NULL,
    items        jsonb NOT NULL,  -- {item_id or raw barcode: count}
    missing      jsonb NOT NULL,
    extra        jsonb NOT NULL,
    wrong        jsonb NOT NULL,
    unread       integer NOT NULL,
    visual_count integer NOT NULL,
    inspected_at timestamptz NOT NULL,
    received_at  timestamptz NOT NULL DEFAULT now(),
    image        bytea  -- JPEG of the frame at Xong
);
CREATE INDEX IF NOT EXISTS inspections_box_idx ON inspections (box_id, inspected_at DESC);
